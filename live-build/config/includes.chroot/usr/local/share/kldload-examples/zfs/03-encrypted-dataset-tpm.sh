#!/usr/bin/env bash
# 03-encrypted-dataset-tpm.sh — create a native-encrypted ZFS dataset
# with the key sealed to TPM so it auto-unlocks at boot (no operator
# passphrase prompt) but stays sealed to THIS hardware.
#
# Threat model:
#   * Disk theft / forensic analysis: protected (data unreadable without TPM)
#   * Server compromise while running: NOT protected (key is in kernel)
#   * Recovery from total host failure: planned — you also need to
#     escrow the key offline (e.g., printed paper backup)
#
# kldload ships with TPM tools + a `tpm-secret` wrapper. This script
# uses tpm-secret to seal a randomly-generated 32-byte key.
set -euo pipefail

DATASET="${1:?usage: $0 <dataset>}"
KEY_NAME="zfs-key-$(echo "$DATASET" | tr '/' '-')"

# ── Generate + seal a random key ──────────────────────────────────────
if [[ -f "/var/lib/kldload/secrets/${KEY_NAME}.tpm" ]]; then
    echo "ERROR: TPM blob ${KEY_NAME}.tpm already exists — destroy first to re-roll the key"
    exit 1
fi

echo "[1/4] Generating 32-byte key + sealing to TPM"
KEYFILE=$(mktemp --tmpdir=/dev/shm "zfskey.XXXXXX")
trap 'shred -u "$KEYFILE"' EXIT
dd if=/dev/urandom of="$KEYFILE" bs=32 count=1 status=none

tpm-secret seal --name "$KEY_NAME" --file "$KEYFILE"

# ── Create dataset with native encryption ─────────────────────────────
echo "[2/4] Creating $DATASET with aes-256-gcm encryption"
zfs create \
    -o encryption=aes-256-gcm \
    -o keyformat=raw \
    -o keylocation="file://${KEYFILE}" \
    "$DATASET"

# ── Replace keylocation with a TPM-unsealing script ───────────────────
# zfs reads keylocation on `zfs load-key`. We point it at a script that
# tpm-unseals on demand, writes the key to a tmpfs path, ZFS reads it,
# the temp path is then shredded.
KEYHELPER="/etc/zfs/keys/${KEY_NAME}.sh"
echo "[3/4] Installing TPM-unseal keylocation helper at $KEYHELPER"
sudo mkdir -p "$(dirname "$KEYHELPER")"
sudo tee "$KEYHELPER" >/dev/null <<EOF
#!/bin/bash
# Auto-generated by 03-encrypted-dataset-tpm.sh — DO NOT EDIT
# Called by zfs load-key to unseal $DATASET's key from TPM at boot.
set -e
KEY=\$(mktemp --tmpdir=/dev/shm)
trap 'shred -u "\$KEY"' EXIT
tpm-secret unseal --name $KEY_NAME --output "\$KEY"
cat "\$KEY"
EOF
sudo chmod 700 "$KEYHELPER"

zfs set "keylocation=file://${KEYHELPER}" "$DATASET"

# ── Test the unseal path ──────────────────────────────────────────────
echo "[4/4] Testing TPM unseal — unmount, unload key, reload from TPM"
zfs umount "$DATASET" || true
zfs unload-key "$DATASET"
zfs load-key "$DATASET"
zfs mount "$DATASET"

echo
echo "Done. $DATASET is mounted + TPM-sealed."
echo "  At boot:  systemd-zfs-mount.service will load-key automatically (TPM-driven)"
echo "  Manual unlock test: zfs unload-key $DATASET && zfs load-key $DATASET"
echo "  Off-host backup: BACK UP /var/lib/kldload/secrets/${KEY_NAME}.tpm — it's the only thing"
echo "                    that can unseal this dataset's key, and only on this exact TPM."
echo "                    Lose both and the data is gone."
